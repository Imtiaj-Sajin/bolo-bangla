const DICT: Record<Lang, Record<UiKey, string>> = { en, id };

export function format(s: string, vars?: Record<string, string | number>): string {
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
}

export function tx(key: UiKey, vars?: Record<string, string | number>, lang = getProgress().profile.lang): string {
  return format(DICT[lang][key], vars);
}

/** Hook: re-renders when the course language changes. */
export function useT() {
  const lang = useProgress().profile.lang;
  return (key: UiKey, vars?: Record<string, string | number>) => format(DICT[lang][key], vars);
}

